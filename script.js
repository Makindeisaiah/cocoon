  gallery = [...document.querySelectorAll("[data-gallery]")];
let active = 0,
  lastFocus = null;
function setLang(next) {
  lang = next;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.dataset.i18n;
    if (translations[lang][k]) el.innerHTML = translations[lang][k];
  });
  langBtn.textContent = lang === "fr" ? "EN / FR" : "EN / FR";
  langBtn.setAttribute(
    "aria-label",
    lang === "fr" ? "Switch to English" : "Passer en français",
  );
  try {
    localStorage.setItem("cocoon-lang", lang);
  } catch (e) {}
}
try {
  const saved = localStorage.getItem("cocoon-lang");
  if (saved === "en" || saved === "fr") lang = saved;
} catch (e) {}
setLang(lang);
langBtn.addEventListener("click", () => setLang(lang === "fr" ? "en" : "fr"));
function closeMenu() {
  nav.classList.remove("open");
  menu.setAttribute("aria-expanded", "false");
  document.body.classList.remove("menu-open");
}
menu.addEventListener("click", () => {
  const open = menu.getAttribute("aria-expanded") !== "true";
  menu.setAttribute("aria-expanded", String(open));
  nav.classList.toggle("open", open);
  document.body.classList.toggle("menu-open", open);
});
nav
  .querySelectorAll("a")
  .forEach((a) => a.addEventListener("click", closeMenu));
window.addEventListener("resize", () => {
  if (innerWidth > 740) closeMenu();
});
